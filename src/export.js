import fs from "node:fs";
import path from "node:path";

const START = "<!-- agentmem:start -->";
const END = "<!-- agentmem:end -->";
const EXPORT_TYPES = ["convention", "decision", "gotcha"];
const HEADINGS = { convention: "Conventions", decision: "Decisions", gotcha: "Gotchas" };

export const TARGETS = {
  agents: { file: "AGENTS.md" },
  claude: { file: "CLAUDE.md" },
  copilot: { file: ".github/copilot-instructions.md" },
  cursor: { file: ".cursor/rules/agentmem.mdc", whole: true },
};

export function renderRules(memories) {
  const chosen = memories.filter((m) => EXPORT_TYPES.includes(m.type) || m.pinned);
  const lines = ["## Project memory (agentmem)", "", "Generated by `agentmem export`. Edit the memories, not this block."];
  const guards = chosen.filter((m) => m.guard);
  if (guards.length) {
    lines.push("", "### Guardrails");
    for (const m of guards) lines.push(`- ${m.guard === "block" ? "Never edit" : "Ask before editing"} \`${m.files.join("`, `")}\`: ${m.title}. ${m.body}`);
  }
  for (const type of EXPORT_TYPES) {
    const items = chosen.filter((m) => m.type === type && !m.guard);
    if (items.length) lines.push("", `### ${HEADINGS[type]}`, ...items.map((m) => `- **${m.title}**: ${m.body.replace(/\n+/g, " ")}`));
  }
  return lines.join("\n");
}

export function upsertBlock(existing, block) {
  const wrapped = `${START}\n${block}\n${END}`;
  const re = new RegExp(`${START}[\\s\\S]*?${END}`);
  if (re.test(existing)) return existing.replace(re, wrapped);
  return existing.trim() ? `${existing.trimEnd()}\n\n${wrapped}\n` : `${wrapped}\n`;
}

export function exportRules(store, targets = ["agents"], { includeLocal = false } = {}) {
  const unknown = targets.filter((t) => !TARGETS[t]);
  if (unknown.length) throw new Error(`unknown target: ${unknown.join(", ")}. Choose from: ${Object.keys(TARGETS).join(", ")}`);
  const memories = store.list().filter((m) => includeLocal || m.scope === "team");
  const block = renderRules(memories);
  return targets.map((t) => {
    const { file, whole } = TARGETS[t];
    const full = path.join(store.project.root, file);
    fs.mkdirSync(path.dirname(full), { recursive: true });
    const content = whole
      ? `---\ndescription: Project memory exported by agentmem\nalwaysApply: true\n---\n\n${block}\n`
      : upsertBlock(fs.existsSync(full) ? fs.readFileSync(full, "utf8") : "", block);
    fs.writeFileSync(full, content);
    return file;
  });
}
